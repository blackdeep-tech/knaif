"""Sample files to run against, copied rather than used in place.

`sandbox/fixtures/<skill>/` holds the corpus's inputs — `clip.mp4`, `clip_no_audio.mp4`,
`audio.mp3` and friends for ffmpeg. They are generated by `just eval-fixtures <skill>` and are
what the executing verifiers grade against.

**The workbench never runs in that directory.** A real (non-dry-run) execution writes files:
re-encodes, trims, overwrites. Doing that in `sandbox/fixtures/` would silently change what every
later eval run measures, and the damage would surface as a model regression in a run that had
nothing to do with the notebook. So the fixtures are copied into the bench's own scratch first,
and only the copy is ever touched.

See docs/plans/2026-09-21-skill-prompt-workbench.md (D5).
"""

from __future__ import annotations

import shutil
from pathlib import Path


def fixture_dir(root: Path | str, skill: str) -> Path:
    """Where `just eval-fixtures <skill>` puts its inputs."""
    return Path(root) / "sandbox" / "fixtures" / skill


def provision(fixtures: Path | str, work_dir: Path | str) -> int:
    """Copy every fixture into *work_dir*, returning how many arrived.

    **Every** fixture, not only the ones an utterance names — matching what the eval lane does,
    and for the reason recorded there: copying only the named inputs is stricter than what
    Python's verifiers see, and the difference gets scored against the runtime instead of
    against the harness.

    A copy, never a link: the point is that writing to the copy cannot reach the source.

    A missing fixture directory returns 0 rather than raising. A skill whose fixtures have not
    been generated yet is still perfectly usable in dry-run, which is the default.
    """
    fixtures, work_dir = Path(fixtures), Path(work_dir)
    if not fixtures.is_dir():
        return 0

    work_dir.mkdir(parents=True, exist_ok=True)
    copied = 0
    for source in sorted(fixtures.rglob("*")):
        if not source.is_file() or source.name.startswith("."):
            continue
        destination = work_dir / source.relative_to(fixtures)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
        copied += 1
    return copied


def ensure(root: Path | str, skill: str, work_dir: Path | str) -> tuple[int, str]:
    """Provision *skill*'s fixtures and say what happened, for the notebook to print."""
    source = fixture_dir(root, skill)
    count = provision(source, work_dir)
    if count:
        return count, f"{count} fixture(s) copied from {source} — the originals are untouched"
    return 0, (
        f"no fixtures at {source}. Dry-run needs none; for a real run, "
        f"generate them with `just eval-fixtures {skill}`"
    )
